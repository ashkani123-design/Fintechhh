/**
 * Checks if the expert profile has all mandatory academic & professional metadata completed.
 */
export function isMetadataComplete(metadata?: InterviewMetadata | null): boolean {
  if (!metadata) return false;
  return Boolean(
    metadata.expertName?.trim() &&
    metadata.expertPosition?.trim() &&
    metadata.organization?.trim() &&
    metadata.experienceYears?.trim() &&
    metadata.educationField?.trim()
  );
}

